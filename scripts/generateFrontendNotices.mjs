function render() {
  const parts = [
    "THIRD-PARTY NOTICES — LegalAId web application",
    "",
    "The LegalAId web application includes the open-source software and icon drawings listed below.",
    "Each is used under its own licence, reproduced in full. Generated by scripts/generateFrontendNotices.mjs.",
    "",
    "=============================================================================",
    "",
    ICONS,
  ];
  const missing = [];
  for (const pkg of productionPackages()) {
    const dir = path.join(FRONTEND, "node_modules", pkg.name);
    const meta = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
    const licence = typeof meta.license === "string" ? meta.license : meta.license?.type || (meta.licenses || []).map((l) => l.type).join(" OR ") || "UNKNOWN";
    const text = licenceText(dir);
    if (!text) missing.push(pkg.name);
    parts.push("", "", `${pkg.name} ${pkg.version}`, `License: ${licence}`, "-".repeat(77), text || `(No licence file ships with this package. Its package.json declares ${licence}.)`);
  }
  return { text: `${parts.join("\n")}\n`, missing };
}

const { text, missing } = render();
if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== text) {
    console.error("frontend/public/third-party-notices.txt is out of date. Run: node scripts/generateFrontendNotices.mjs");
    process.exit(1);
  }
  console.log("third-party notices are up to date");
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${text.length} bytes)${missing.length ? `; no licence file in: ${missing.join(", ")}` : ""}`);
}
