/**
 * generateFrontendNotices.mjs
 *
 * Writes frontend/public/third-party-notices.txt: the licence and copyright
 * notice of every package that ships in the frontend bundle (production
 * dependencies, direct and transitive), plus the icon sets whose drawings are
 * copied into frontend/src/utils/icons.jsx. MIT, ISC and BSD all require the
 * notice to travel with the code; the bundle is the code users receive.
 *
 *   node scripts/generateFrontendNotices.mjs          write the file
 *   node scripts/generateFrontendNotices.mjs --check  exit 1 if it is out of date
 */
import fs from "fs";
import path from "path";
import { execFileSync } from "child_process";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const FRONTEND = path.join(ROOT, "frontend");
const OUT = path.join(FRONTEND, "public", "third-party-notices.txt");

function productionPackages() {
  const json = execFileSync("npm", ["ls", "--omit=dev", "--all", "--json"], { cwd: FRONTEND, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
  const seen = new Map();
  (function walk(deps = {}) {
    for (const [name, info] of Object.entries(deps)) {
      const key = `${name}@${info.version}`;
      if (!seen.has(key)) seen.set(key, { name, version: info.version });
      walk(info.dependencies);
    }
  })(JSON.parse(json).dependencies);
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function licenceText(dir) {
  const file = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  return file ? fs.readFileSync(path.join(dir, file), "utf8").trim() : null;
}

