/**
 * documentWithdrawals.js
 *
 * Two related registers, kept apart because they end at different times.
 *
 * WITHDRAWN_DOCUMENT_TYPES — a type withdrawn from public generation because a
 * shipped output was found to be substantively wrong while the validator called
 * it clean. Ends when the type is restored (after advocate approval).
 *
 *   - no new document of the type can be started through any public route;
 *   - every validation of a document of the type is reported as REQUIRES REVIEW
 *     with no score.
 *
 * SUPERSEDED_OUTPUTS — documents produced by the defective version. Does NOT end
 * when the type is restored: a term sheet generated on 1 October is as wrong
 * after the rebuilt version is approved as it was before. A draft is recognised
 * as current by `metadata.instrument_version`, which the engine stamps from the
 * drafting policy; anything without the current stamp is superseded.
 *
 *   - its validation never shows a score or a clean label again;
 *   - every download (DOCX, PDF, TXT) carries a warning at the top and the end;
 *   - the stored document and its validation history are not modified. The
 *     marks are applied on read and on export only, so the original stays
 *     auditable and nothing is silently "fixed".
 *
 * Shared between backend and frontend; keep it dependency-free.
 */

