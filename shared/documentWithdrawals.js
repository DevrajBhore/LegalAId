export const WITHDRAWAL_RULE_ID = "DOCUMENT_TYPE_WITHDRAWN";
export const SUPERSEDED_RULE_ID = "OUTPUT_SUPERSEDED";

export function withdrawalFor(documentType) {
  if (!documentType) return null;
  return WITHDRAWN_DOCUMENT_TYPES[String(documentType)] || null;
}

export function isWithdrawn(documentType) {
  return withdrawalFor(documentType) !== null;
}

/**
 * The superseded-output record for this draft, or null if the draft is current
 * (or its type has none). A draft that cannot show it is current — no draft at
 * all, or no stamp — is treated as superseded: the safe reading of a document
 * whose provenance is unknown.
 */
export function supersededOutputFor(documentType, draft) {
  const record = SUPERSEDED_OUTPUTS[String(documentType || draft?.document_type || "")];
  if (!record) return null;
  const version = draft?.metadata?.instrument_version;
  if (version !== record.current_instrument_version) return record;
  const ids = (draft?.clauses || []).map((c) => c?.clause_id);
  return ids.some((id) => record.superseded_clause_ids.includes(id)) ? record : null;
}

export function withdrawalIssue(documentType) {
  const w = withdrawalFor(documentType);
  if (!w) return null;
  return {
    rule_id: WITHDRAWAL_RULE_ID,
    severity: "HIGH",
    message: w.user_message,
    suggestion: "Have a qualified advocate review this document before you sign or rely on it.",
    manual_review_required: true,
    layer: "withdrawal",
  };
}

function supersededIssue(record) {
  return {
    rule_id: record.rule_id,
    severity: "HIGH",
    message: record.user_message,
    suggestion: "Have a qualified advocate review this document before you sign, send or rely on it.",
    manual_review_required: true,
    layer: "withdrawal",
  };
}

/**
 * Return a copy of a validation result with its assurance withdrawn, when the
 * type is withdrawn or the draft is a superseded output.
 *
 * Idempotent; a no-op (same object) when neither applies. Works on full results,
 * on stored summaries, and on null (a saved draft never validated still gets the
 * review requirement). `draft` is optional: without it a withdrawn type is still
 * marked, and a type with superseded outputs is treated as superseded.
 */
export function withValidationAssuranceWithdrawn(validation, documentType, draft) {
  const withdrawal = withdrawalFor(documentType);
  const superseded = supersededOutputFor(documentType, draft);
  if (!withdrawal && !superseded) return validation;
  if (validation && validation.assurance_withdrawn) return validation;

  const base = validation && typeof validation === "object" ? validation : {};
  const issue = superseded ? supersededIssue(superseded) : withdrawalIssue(documentType);
  const advisory = Array.isArray(base.advisoryIssues) ? base.advisoryIssues : [];
  const hasIssue = advisory.some((i) => i?.rule_id === issue.rule_id);
  const advisoryIssues = hasIssue ? advisory : [issue, ...advisory];
  const added = hasIssue ? 0 : 1;
  const bump = (n) => (typeof n === "number" ? n + added : added);

  return {
    ...base,
    score: null,
    // D4.46: one of the release outcomes. A withdrawn or superseded output needs
    // a lawyer's review whatever its findings; a blocking finding still wins.
    certification: (base.blockingIssues?.length ?? 0) > 0 ? "Blocked" : "Requires legal review",
    release_outcome: (base.blockingIssues?.length ?? 0) > 0 ? "BLOCKED" : "REQUIRES_LEGAL_REVIEW",
    certified: false,
    checks_passed: false,
    assurance_withdrawn: {
      document_type: String(documentType),
      reason_code: superseded ? SUPERSEDED_RULE_ID : WITHDRAWAL_RULE_ID,
      withdrawn_on: superseded ? superseded.superseded_on : withdrawal.withdrawn_on,
      reason: superseded ? superseded.user_message : withdrawal.reason,
      // Kept for audit only. It is the figure the engine gave before the output
      // was found defective, and it must not be displayed as a quality score.
      superseded_assessment:
        base.score != null || base.certification
          ? { score: base.score ?? null, certification: base.certification ?? null }
          : null,
    },
    advisoryIssues,
    advisory_issues: advisoryIssues,
    issueCount: bump(base.issueCount),
    openIssueCount: bump(base.openIssueCount),
    open_issue_count: bump(base.open_issue_count),
    summary: {
      ...(base.summary || {}),
      advisory: bump(base.summary?.advisory),
      total: bump(base.summary?.total),
    },
  };
}
